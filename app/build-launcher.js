#!/usr/bin/env node
// build-launcher.js — OPTIONAL packaging: install the mcpctl node launcher into
// app/dist (the dir on PATH).
//
// The default packaging is the self-contained exe built by: node app/build.js
//
//   app/dist/mcpctl      (POSIX: shebang JS)  ->  node app/bin/mcpctl.js
//   app/dist/mcpctl.cmd  (cmd.exe/PowerShell) ->  node app\bin\mcpctl.js %*
//
// Why you might prefer this: it is ~1 KB of text instead of a ~92 MB copy of
// node.exe with the Authenticode signature stripped and a blob injected as a PE
// resource (the shape AV heuristics scan, block, or quarantine), and it re-reads
// mcpctl.js on every run, so a source edit takes effect with no rebuild step.
//
// Why you might not: it requires `node` on PATH — the exe bundles its own.
//
// The two are mutually exclusive on purpose: cmd.exe resolves .exe before .cmd
// (PATHEXT) while Git Bash resolves the extensionless name first, so a directory
// holding both would run a different binary per shell. This script therefore
// removes app/dist/mcpctl.exe.
'use strict';

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const IMPL = path.join(ROOT, 'mcpctl.js');
const ENTRY = path.join(ROOT, 'bin', 'mcpctl.js');
const DIST = path.join(ROOT, 'dist');
const SH = path.join(DIST, 'mcpctl'); // bash / Git Bash / WSL
const CMD = path.join(DIST, 'mcpctl.cmd'); // cmd.exe / PowerShell
const STALE_EXE = path.join(DIST, 'mcpctl.exe');

function die(msg) { console.error('build-launcher: ' + msg); process.exit(1); }

for (const f of [IMPL, ENTRY]) if (!fs.existsSync(f)) die('missing ' + f);

// 0. both files must parse — a syntax error here is a dead CLI on PATH.
for (const f of [IMPL, ENTRY]) execFileSync(process.execPath, ['--check', f], { stdio: 'inherit' });

fs.mkdirSync(DIST, { recursive: true });

// 1. shims. "$@" / %* keep the caller's own quoting intact, and the errorlevel
//    is propagated explicitly so mcpctl's exit codes (0-4) survive the shim —
//    scripts in this repo branch on those.
//    A shebang script, not a bash wrapper: Git Bash / WSL / *nix exec it directly,
//    so a run costs exactly one node process. Going through `bash` added a whole
//    shell process per call (~45 ms measured on Windows).
const sh = `#!/usr/bin/env node
// mcpctl (POSIX launcher) -- runs the CLI on node.
// Generated by app/build-launcher.js; do not edit by hand.
// No packed executable, so there is nothing large/unsigned for AV to scan,
// block, or quarantine on launch.
'use strict';
require(require('path').join(__dirname, '..', 'bin', 'mcpctl.js'));
`;
const cmd = `@echo off
rem mcpctl.cmd (Windows launcher) -- runs the CLI on node.
rem Generated by app\\build-launcher.js; do not edit by hand.
rem No packed executable, so there is nothing large/unsigned for AV to scan,
rem block, or quarantine on launch.
setlocal
node "%~dp0..\\bin\\mcpctl.js" %*
exit /b %errorlevel%
`;

fs.writeFileSync(SH, sh);
fs.chmodSync(SH, 0o755); // exec bit matters on Git Bash / WSL / *nix checkouts
fs.writeFileSync(CMD, cmd);

// 2. the exe would shadow the launcher in cmd.exe (PATHEXT puts .exe before
//    .cmd), and would make bash and cmd disagree — remove it.
let removed = false;
if (fs.existsSync(STALE_EXE)) {
  const mb = (fs.statSync(STALE_EXE).size / 1048576).toFixed(0);
  fs.rmSync(STALE_EXE);
  removed = true;
  console.log(`  removed mcpctl.exe (${mb} MB, would shadow the launcher)`);
}

// 3. self-test: really run the entrypoint through node and check it answers.
let help = '';
try {
  help = execFileSync(process.execPath, [ENTRY, 'help'], { encoding: 'utf8' });
} catch (e) {
  die('self-test failed: ' + ENTRY + ' help -> ' + String((e && e.message) || e).split('\n')[0]);
}
const banner = (help.split('\n')[0] || '').trim();
if (!/^mcpctl\b/.test(banner)) die('self-test failed: unexpected help banner: ' + JSON.stringify(banner));

console.log('built node launcher:');
console.log('  ' + path.relative(ROOT, SH) + '      -> node bin/mcpctl.js  (shebang js, ' + Buffer.byteLength(sh) + ' B)');
console.log('  ' + path.relative(ROOT, CMD) + '  -> node bin\\mcpctl.js  (cmd shim, ' + Buffer.byteLength(cmd) + ' B)');
console.log('  impl   ' + path.relative(ROOT, IMPL) + ' (' + fs.statSync(IMPL).size + ' B, read from source on every run)');
console.log('  runtime node ' + process.version + ' (' + process.execPath + ')');
console.log('  self-test  help ok: "' + banner + '"');
if (removed) console.log('  note: re-run this build if anything recreates app/dist/mcpctl.exe');
console.log('run: mcpctl help      (or: node app/bin/mcpctl.js help)');
